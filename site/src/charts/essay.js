/** 95% band behind a trend line (bandColor when the chart's area fill shares the line's hue),
 *  the thin-data stretch of the line dimmed, and a note. */
function uncertainty(svg, x, y, key, color, path, bandColor = color) {
  // Era notes anchored near the axis start can spill over the y labels.
  const left = x.range()[0] + 4;
  svg.selectAll('text.annot').each(function () {
    const b = this.getBBox();
    if (b.width && b.x < left) this.setAttribute('x', +this.getAttribute('x') + (left - b.x));
  });
  const ci = (SERIES_CI?.[key] || []).filter((c) => c[0] >= CHART_X0);
  if (!ci.length) return null;
  const [d0, d1] = y.domain(),
    lo = Math.min(d0, d1),
    hi = Math.max(d0, d1);
  const clamp = (v) => Math.max(lo, Math.min(hi, v));
  const band = svg
    .insert('path', () => path.node())
    .datum(ci)
    .attr('class', 'ci-band')
    .attr(
      'd',
      d3
        .area()
        .x((d) => x(d[0]))
        .y0((d) => y(clamp(d[1])))
        .y1((d) => y(clamp(d[2])))
        .curve(d3.curveMonotoneX),
    )
    .attr('fill', bandColor)
    .attr('opacity', 0);
  const fragile = ci.filter((c) => c[3] < FRAGILE_N);
  const solid = ci.find((c) => c[3] >= FRAGILE_N && c[0] > fragile[fragile.length - 1]?.[0]);
  if (fragile.length && solid) {
    const [r0, r1] = x.range(),
      at = (v) => `${((100 * (x(v) - r0)) / (r1 - r0)).toFixed(2)}%`;
    const g = svg
      .append('defs')
      .append('linearGradient')
      .attr('id', `ci-fade-${key}`)
      .attr('gradientUnits', 'userSpaceOnUse')
      .attr('x1', r0)
      .attr('x2', r1)
      .attr('y1', 0)
      .attr('y2', 0);
    [
      [0, 0.4],
      [at(fragile[fragile.length - 1][0]), 0.4],
      [at(solid[0]), 1],
      ['100%', 1],
    ].forEach(([o, a]) =>
      g.append('stop').attr('offset', o).attr('stop-color', color).attr('stop-opacity', a),
    );
    path.attr('stroke', `url(#ci-fade-${key})`);
    svg
      .append('text')
      .attr('class', 'annot thin-note')
      .attr('text-anchor', 'start')
      .attr('x', x(fragile[0][0]))
      .attr('y', y(lo) - 8)
      .text(t('annot_thin_data'));
  }
  return band;
}
