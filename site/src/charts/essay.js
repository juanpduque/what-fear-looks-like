/** Readout suffix: the point's 95% interval and how many posters back it. */
function ciNote(key, year) {
  const c = (SERIES_CI?.[key] || []).find((r) => r[0] === year);
  return c ? ` · ${t('readout_ci', { lo: c[1], hi: c[2], n: c[3].toLocaleString() })}` : '';
}

